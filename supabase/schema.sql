create table if not exists public.assets (
  id bigint generated by default as identity primary key,
  token_id text,
  nft_address text,
  name text not null,
  description text not null default '',
  category text not null,
  image text not null,
  origin text not null default '',
  creator text not null,
  owner text not null,
  price_eth text not null default '',
  price_wei text not null default '',
  royalty_bps integer not null default 500,
  status text not null default 'Draft',
  is_listed boolean not null default false,
  is_demo boolean not null default false,
  token_uri text not null default '',
  tx_hash text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists assets_contract_token
  on public.assets (nft_address, token_id)
  where token_id is not null;

create unique index if not exists assets_demo_name
  on public.assets (name)
  where is_demo = true;

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  asset_id bigint not null references public.assets (id) on delete cascade,
  type text not null,
  tx_hash text not null unique,
  from_address text not null,
  to_address text not null default '',
  amount_wei text not null default '',
  created_at timestamptz not null default now()
);

alter table public.assets enable row level security;
alter table public.transactions enable row level security;

